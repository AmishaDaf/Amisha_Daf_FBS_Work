#1. and  : If both operands are True then return True, otherwise return False

print(True and True)  #T

#2. or : If both operands are False then return False, otherwise return True

print(False or True)    #T


#3. not : Opposite of operand
print(not True)         #F


#Falsy : False, None, 0, blank value like: '', []
#eg. print('' or 10)     #10